#!/usr/bin/env node
/**
 * Generate the agent-facing okra CLI noun/verb reference (W.4.24e #460).
 *
 * Source of truth: the committed `src/cli/resource-catalog.generated.json`
 * fixture, which is itself generated from the API's `/v1/resources` catalog
 * (see `apps/api/packages/server/scripts/generate-resource-catalog-fixture.mjs`).
 * Generating the reference from the fixture means it CANNOT drift from the API
 * surface — the #459 contract test keeps the fixture and the commander tree in
 * sync, and this script keeps the skill reference in sync with the fixture.
 *
 * Scope: the agent surface = `core` + `advanced` tiers. `internal` primitives
 * (sessions, layerizations) are scoped out of the agent loop and omitted.
 *
 * Output: `skills/okra-agent/CLI_REFERENCE.generated.md`, a sibling file linked
 * from `skills/okra-agent/SKILL.md`. Unlike `generate-cli-docs.mjs` (which shells
 * the built binary for `--help` text), this reads the static fixture, so it needs
 * no build and is fully deterministic — re-running produces ZERO diff.
 *
 * Usage:
 *   node ./scripts/generate-cli-reference.mjs           # write the reference
 *   node ./scripts/generate-cli-reference.mjs --check    # CI drift gate
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const packageDir = resolve(__dirname, '..');
const fixturePath = resolve(packageDir, 'src/cli/resource-catalog.generated.json');
const outPath = resolve(packageDir, 'skills/okra-agent/CLI_REFERENCE.generated.md');
const checkMode = process.argv.includes('--check');

const fixture = JSON.parse(readFileSync(fixturePath, 'utf8'));

/** Default CLI form for a noun operation when the fixture carries no explicit hint. */
function nounOpCli(nounName, op) {
  if (op.cliOmit) return null; // API/SDK-only — no okra command to surface.
  if (op.cli) return op.cli;
  return `okra ${nounName} ${op.action}`;
}

/** Default CLI form for an action when the fixture carries no explicit hint. */
function actionCli(action) {
  const hinted = action.operations.find((op) => op.cli)?.cli;
  if (hinted) return hinted;
  return `okra ${action.name}`;
}

const TIER_LABEL = { core: 'core', advanced: 'advanced' };

function isAgentSurface(entry) {
  return entry.tier === 'core' || entry.tier === 'advanced';
}

const nouns = fixture.nouns.filter(isAgentSurface);
const actions = fixture.actions.filter(isAgentSurface);

const lines = [
  '# okra CLI reference (GENERATED)',
  '',
  '<!-- GENERATED by packages/okrapdf/scripts/generate-cli-reference.mjs from',
  '     src/cli/resource-catalog.generated.json (the /v1/resources catalog).',
  '     Do not edit by hand. Regenerate: pnpm --filter @okrapdf/sdk docs:cli:reference -->',
  '',
  'The agent surface of the `okra` CLI, derived from the API resource catalog',
  '(`/v1/resources`). `core` = the agent-first loop; `advanced` = available but',
  'outside the default loop. `internal` primitives are intentionally omitted.',
  '',
  '## Resource nouns',
  '',
];

for (const noun of nouns) {
  const aliasNote = noun.aliases.length > 0 ? ` (aliases: ${noun.aliases.join(', ')})` : '';
  lines.push(`### \`${noun.name}\` — ${TIER_LABEL[noun.tier]}${aliasNote}`);
  lines.push('');
  lines.push(noun.description);
  lines.push('');
  for (const op of noun.operations) {
    const cmd = nounOpCli(noun.name, op);
    lines.push(cmd ? `- \`${cmd}\` — ${op.action}` : `- _(API/SDK only)_ — ${op.action}`);
  }
  lines.push('');
}

lines.push('## Action verbs');
lines.push('');
lines.push('Verb-first commands that create work (often a job).');
lines.push('');

for (const action of actions) {
  lines.push(`- \`${actionCli(action)}\` — ${TIER_LABEL[action.tier]} · ${action.description}`);
}
lines.push('');

const generated = lines.join('\n');

if (checkMode) {
  let current = '';
  try {
    current = readFileSync(outPath, 'utf8');
  } catch {
    current = '';
  }
  if (current !== generated) {
    process.stderr.write(
      'okra CLI reference is out of date. Run `pnpm --filter @okrapdf/sdk docs:cli:reference`.\n',
    );
    process.exit(1);
  }
  process.stdout.write('okra CLI reference is up to date.\n');
  process.exit(0);
}

writeFileSync(outPath, generated);
process.stdout.write(`Wrote ${outPath} (${nouns.length} nouns, ${actions.length} actions)\n`);
